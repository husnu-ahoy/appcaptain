function sample(n: number, s: SampleInput): ExperienceDTO {
  return {
    id: s.id,
    captainId: 'ornek',
    status: ExperienceStatus.ACTIVE,
    progress: { currentStep: ExperienceStep.MEDIA, completedSteps: [...EXPERIENCE_STEP_ORDER], isReadyForSubmit: true },
    category: s.category,
    secondaryCategories: s.secondaryCategories ?? [],
    productType: s.productType,
    title: s.title,
    referenceCode: `ORNEK-${String(n).padStart(3, '0')}`,
    shortDescription: s.shortDescription,
    fullDescription: s.description.join('\n\n'),
    highlights: s.highlights,
    keywords: s.keywords,
    included: s.included,
    notIncluded: s.notIncluded,
    notAllowed: s.notAllowed ?? ['Cam şişe', 'Kapalı alanda sigara'],
    toBring: s.toBring ?? SEA_DAY,
    knowBeforeYouGo: s.knowBeforeYouGo ?? [ON_TIME, WEATHER],
    emergencyContactPhone: null,
    difficultyLevel: s.difficultyLevel ?? ExperienceDifficultyLevel.EASY,
    durationMinutes: s.durationMinutes,
    meetingPoint: s.meetingPoint,
    meetingPointLat: s.lat,
    meetingPointLng: s.lng,
    meetingTime: s.meetingTime,
    endPoint: '',
    endPointLat: null,
    endPointLng: null,
    isSameEndPoint: true,
    languages: s.languages,
    minParticipants: s.minParticipants ?? 1,
    maxParticipants: s.maxParticipants,
    minAge: s.minAge ?? null,
    ticketType: 'mobile',
    requiredEquipment: s.requiredEquipment ?? [],
    accessibilityInfo: s.accessibilityInfo ?? '',
    accessibilityOptions: [],
    pickupOffered: !!s.pickup,
    pickupAreas: s.pickup?.areas ?? '',
    pickupFee: s.pickup?.fee ?? null,
    basePrice: s.basePrice,
    currency: 'TRY',
    pricingType: s.pricingType,
    childDiscountPercent: s.childDiscountPercent ?? null,
    currencyLocked: false,
    displayCurrency: 'EUR',
    cancellationPolicy: s.cancellationPolicy,
    cancellationPolicyText: null,
    cancellationTiers: TIERS[s.cancellationPolicy],
    coverPhotoUrl: s.coverPhotoUrl,
    photoUrls: s.photoUrls,
    videoUrl: null,
    reviewNote: null,
    createdAt: '2026-11-23T00:00:00.000Z',
    updatedAt: '2026-11-23T00:00:00.000Z',
    customerInfoFields: s.pickup
      ? [
          {
            id: `${s.id}-otel`,
            label: 'Otel adı',
            fieldType: CustomerInfoFieldType.TEXT,
            required: false,
            helpText: 'Otelden alınma istiyorsan alınma saatini bildirebilmemiz için.',
            options: [],
            sortOrder: 0,
          },
        ]
      : [],
    seasonalPricingRules: [],
  }
}

